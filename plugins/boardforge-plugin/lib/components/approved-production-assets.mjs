export function approvedAssetFor(mpn, { requiredPinCount } = {}) {
  const asset = approvedProductionAssets[mpn] || null;
  if (!asset) return null;
  if (requiredPinCount && asset.physicalPinCount !== requiredPinCount)
    return null;
  return structuredClone(asset);
}
function physicalCount(packageName, pinMap) {
  const text = String(packageName),
    match = text.match(
      /(?:LQFP|SOIC|QFN|WQFN)[-_]?(\d+)|SOT-23-(\d+)|1x(\d+)|(\d+)P/i,
    );
  if (!match) return Object.keys(pinMap).length;
  const count = Number(match.slice(1).find(Boolean));
  if (/2EP/i.test(text)) return count + 2;
  return /QFN/i.test(text) && /EP/i.test(text) ? count + 1 : count;
}
