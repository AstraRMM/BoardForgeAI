const pins = (n) =>
  Array.from({ length: n }, (_, i) => ({
    number: String(i + 1),
    name: String(i + 1),
  }));
const pads = (n) =>
  Array.from({ length: n }, (_, i) => ({ name: String(i + 1) }));
import { productionAssetPinSchema } from "./production-asset-pin-schema.mjs";
const entry = (mpn, symbol, footprint, pinMap, packageName, options = {}) => {
  const pinSchema = productionAssetPinSchema({
    symbolPinMap: options.symbolPinMap || pinMap,
    footprintPadMap: options.footprintPadMap || pinMap,
    pinAliases: options.pinAliases,
    footprintPadAliases: options.footprintPadAliases,
    unconnectedFootprintPads: options.unconnectedFootprintPads,
  });
  return {
    mpn,
    symbol: {
      libId: symbol,
      pins: Object.keys(pinSchema.symbolPinMap).map((number) => ({
        number,
        name: number,
      })),
    },
    footprint: {
      libId: footprint,
      pads: Object.keys(pinSchema.footprintPadMap).map((name) => ({ name })),
    },
    pinMap: Object.freeze(pinMap),
    symbolPinMap: pinSchema.symbolPinMap,
    footprintPadMap: pinSchema.footprintPadMap,
    pinAliases: pinSchema.pinAliases,
    footprintPadAliases: pinSchema.footprintPadAliases,
    unconnectedFootprintPads: pinSchema.unconnectedFootprintPads,
    pinSchema,
    package: packageName,
    physicalPinCount: physicalCount(packageName, pinSchema.footprintPadMap),
    externalAntennaRequirement: options.externalAntennaRequirement || null,
    sourceEvidence: options.sourceEvidence || null,
    applicationLimitations: Object.freeze(options.applicationLimitations || []),
    approval: "boardforge.production-asset-registry.v2",
  };
};

