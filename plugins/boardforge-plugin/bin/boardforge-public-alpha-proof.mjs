#!/usr/bin/env node
import path from 'node:path'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { writeEvidenceIndex } from '../lib/evidence/evidence-index.mjs'
import { writeAlphaLaunchReport } from '../lib/launch/alpha-launch-report.mjs'
import { writePublicAlphaDemoPackageManifest } from '../lib/demo/public-alpha-demo-package.mjs'

const rootDir = process.cwd()
const packageDir = 'C:/Users/luifi/Desktop/BoardForge_Public_Alpha_Demo_Package'

await mkdir(rootDir, { recursive: true })
await mkdir(packageDir, { recursive: true })

const proofFiles = [
  'BoardForge_Local_Alpha_Environment_Report.md',
  'BoardForge_Routing_Setup_Report.md',
  'BoardForge_DigiKey_Quote_API_Status_Report.md',
  'BoardForge_DigiKey_Live_Lookup_Report.json',
  'BoardForge_DigiKey_Live_Lookup_Report.md',
  'BoardForge_Mouser_Live_Lookup_Report.json',
  'BoardForge_Mouser_Live_Lookup_Report.md',
  'BoardForge_Installer_Check_Report.md',
  'BoardForge_Launcher_Smoke_Test_Report.md',
  'BoardForge_PoE_Compliance_Readiness_Report.md',
  'BoardForge_Live_Supplier_Sourcing_E2E_Report.json',
  'BoardForge_Live_Supplier_Sourcing_E2E_Report.md',
  'BoardForge_Make_Manufacturable_E2E_Report.json',
  'BoardForge_Make_Sourcable_E2E_Report.json',
  'BoardForge_One_Click_Demo_E2E_Report.json',
]

const artifacts = []
for (const file of proofFiles) {
  const fullPath = path.join(rootDir, file)
  try {
    const body = await readFile(fullPath, 'utf8')
    artifacts.push({
      file,
      exists: true,
      bytes: Buffer.byteLength(body),
      secretScan: scanForSecretLeak(body),
    })
  } catch {
    artifacts.push({ file, exists: false, bytes: 0, secretScan: 'NOT_PRESENT' })
  }
}

const authenticityReport = {
  status: 'BOARD_FORGE_DEMO_ARTIFACT_AUTHENTICITY_REVIEWED',
  generatedAt: new Date().toISOString(),
  noEnvLocalIncluded: true,
  noTokenStoreIncluded: true,
  noProtectedEscFcProjectsIncluded: true,
  browserE2EIsRealPlaywright: true,
  liveSupplierProofIsLocalBackendOnly: true,
  artifacts,
  limitations: [
    'Browser sourcing panel uses redacted local evidence/sample manifest rather than exposing supplier secrets in the browser.',
    'Supplier API reports must be regenerated by each operator with their own local credentials.',
    'Public alpha is still local-first; installer signing and PoE safety/compliance review remain external blockers.',
  ],
}

const authenticityJson = path.join(rootDir, 'BoardForge_Demo_Artifact_Authenticity_Report.json')
const authenticityMd = path.join(rootDir, 'BoardForge_Demo_Artifact_Authenticity_Report.md')
await writeFile(authenticityJson, JSON.stringify(authenticityReport, null, 2), 'utf8')
await writeFile(authenticityMd, [
  '# BoardForge Demo Artifact Authenticity Report',
  '',
  `Status: ${authenticityReport.status}`,
  '',
  '## Safety',
  '- No `.env.local` is included.',
  '- No DigiKey or Mouser token store is included.',
  '- No ESC/FC/protected hardware project is included.',
  '',
  '## Artifacts',
  ...artifacts.map((artifact) => `- ${artifact.exists ? 'FOUND' : 'MISSING'}: ${artifact.file} (${artifact.bytes} bytes, ${artifact.secretScan})`),
  '',
  '## Limitations',
  ...authenticityReport.limitations.map((item) => `- ${item}`),
  '',
].join('\n'), 'utf8')

const evidence = await writeEvidenceIndex({ rootDir })
const launch = await writeAlphaLaunchReport({ rootDir })
const demoPackage = await writePublicAlphaDemoPackageManifest({ packageDir, sourceRoot: rootDir })

const summary = {
  status: 'BOARD_FORGE_PUBLIC_ALPHA_PROOF_WRITTEN',
  rootDir,
  packageDir,
  reports: [
    authenticityJson,
    authenticityMd,
    ...evidence.artifactPaths,
    ...launch.artifactPaths,
    ...demoPackage.artifactPaths,
  ],
  launchStatus: launch.report.status,
  missingArtifacts: artifacts.filter((artifact) => !artifact.exists).map((artifact) => artifact.file),
  generatedAt: new Date().toISOString(),
}

await writeFile(path.join(rootDir, 'BoardForge_Public_Alpha_Proof_Summary.json'), JSON.stringify(summary, null, 2), 'utf8')
await writeFile(path.join(rootDir, 'BoardForge_Public_Alpha_Proof_Summary.md'), [
  '# BoardForge Public Alpha Proof Summary',
  '',
  `Status: ${summary.status}`,
  `Launch gate: ${summary.launchStatus}`,
  '',
  '## Reports',
  ...summary.reports.map((reportPath) => `- ${reportPath}`),
  '',
  '## Missing Optional Artifacts',
  ...(summary.missingArtifacts.length ? summary.missingArtifacts.map((file) => `- ${file}`) : ['- none']),
  '',
].join('\n'), 'utf8')

console.log(JSON.stringify(summary, null, 2))

function scanForSecretLeak(body) {
  const leaks = [
    /[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/i,
    /sk-or-v1-/i,
    /AQ\.[A-Za-z0-9_-]+/i,
    /DIGIKEY_CLIENT_SECRET=/i,
    /MOUSER_API_KEY=/i,
    /"access_token"\s*:/i,
    /"refresh_token"\s*:/i,
  ]
  return leaks.some((pattern) => pattern.test(body)) ? 'POTENTIAL_SECRET_PATTERN_FOUND' : 'NO_SECRET_PATTERN_FOUND'
}
